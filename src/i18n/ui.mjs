const DICT = { en, fr };

/** Returns the dictionary for a language, with a `t(path, vars)` lookup. */
export function useUi(lang) {
  const dict = DICT[lang] ?? DICT.en;
  function t(pathKey, vars = {}) {
    let value = pathKey.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
    if (value == null) value = pathKey.split('.').reduce((o, k) => (o == null ? o : o[k]), DICT.en);
    if (typeof value !== 'string') return value ?? pathKey;
    const filled = value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
    return typo(filled, lang);
  }
  return { t, dict };
}
